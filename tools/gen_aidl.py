# The model: every declaration of every package, and name resolution


class Package:
    def __init__(self, name, version, hash_, decls, root):
        self.name, self.version, self.hash, self.decls, self.root = name, version, hash_, decls, root


class Model:
    def __init__(self):
        self.packages = []
        self.decls = {}
        self.errors = []
        self._values = {}
        self._defaultable = {}

    def load(self, aidl_root, pkg, version):
        root = os.path.join(aidl_root, pkg, version)
        if not os.path.isdir(root):
            raise GenError("%s: no frozen API directory" % root)
        hash_path = os.path.join(root, ".hash")
        with open(hash_path, encoding="utf-8") as f:
            hashes = [l.strip() for l in f.read().splitlines() if l.strip()]
        if not hashes:
            raise GenError("%s: empty" % hash_path)
        files = []
        for dirpath, _, names in os.walk(root):
            for n in names:
                if n.endswith(".aidl"):
                    files.append(os.path.join(dirpath, n))
        files.sort(key=lambda p: os.path.relpath(p, root).replace(os.sep, "/"))
        decls = []
        for path in files:
            rel = os.path.relpath(path, aidl_root).replace(os.sep, "/")
            with open(path, encoding="utf-8") as f:
                src = f.read()
            file_pkg, imports, file_decls = Parser(lex(src, rel)).file()
            if file_pkg != pkg:
                raise GenError("%s: package %s in %s's directory" % (rel, file_pkg, pkg))
            for d in file_decls:
                for x in d.all():
                    x.imports = imports
                    if x.fq in self.decls:
                        raise GenError("%s: %s declared twice" % (x.where, x.fq))
                    if rust_name(x) in RESERVED_TYPE_NAMES:
                        raise GenError("%s: the type name %s is reserved by the generated code" % (x.where, rust_name(x)))
                    self.decls[x.fq] = x
                decls.append(d)
        # The last hash is the one the frozen build compiles in.
        self.packages.append(Package(pkg, int(version), hashes[-1], decls, root))

    def lookup(self, name, scope):
        if name in self.decls:
            return self.decls[name]
        s = scope
        while s is not None:
            cand = s.fq + "." + name
            if cand in self.decls:
                return self.decls[cand]
            s = s.outer
        cand = scope.pkg + "." + name
        if cand in self.decls:
            return self.decls[cand]
        first = name.split(".")[0]
        for imp in scope.imports:
            if imp.split(".")[-1] == first:
                cand = imp + name[len(first):]
                if cand in self.decls:
                    return self.decls[cand]
        return None

    def resolve(self, tr, scope):
        nullable = "nullable" in tr.ann
        if tr.dims:
            inner = TypeRef(tr.name, tr.args, tr.dims[1:], {k: v for k, v in tr.ann.items() if k != "nullable"}, tr.where)
            elem = self.resolve(inner, scope)
            fixed = None
            if tr.dims[0] is not None:
                fixed = self.eval(tr.dims[0], scope)[0]
                if not isinstance(fixed, int) or fixed < 0:
                    raise GenError("%s: a fixed array size must be a non-negative integer" % tr.where)
            return self.array(elem, nullable, fixed)
        name = tr.name
        if name in UNSUPPORTED_TYPES:
            raise GenError("%s: %s is not supported" % (tr.where, UNSUPPORTED_TYPES[name]))
        if name == "List":
            if len(tr.args) != 1:
                raise GenError("%s: List takes one type" % tr.where)
            return self.array(self.resolve(tr.args[0], scope), nullable, None)
        if tr.args:
            raise GenError("%s: %s takes no type arguments" % (tr.where, name))
        if name in PRIMS:
            if nullable:
                raise GenError("%s: a @nullable %s" % (tr.where, name))
            return T("prim", prim=name)
        if name == "void":
            return T("void")
        if name == "String":
            return T("string", nullable)
        if name == "ParcelFileDescriptor":
            return T("pfd", nullable)
        if name == "IBinder":
            return T("binder", nullable)
        decl = self.lookup(name, scope)
        if decl is None:
            raise GenError("%s: unknown type %s" % (tr.where, name))
        if decl.kind == "enum" and nullable:
            raise GenError("%s: a @nullable enum" % tr.where)
        return T(decl.kind, nullable, decl=decl)

    @staticmethod
    def array(elem, nullable, fixed):
        if elem.kind == "void":
            raise GenError("an array of void")
        if nullable and elem.kind in ("string", "pfd", "parcelable", "union"):
            # The NDK's @nullable T[]: std::optional<std::vector<std::optional<T>>>.
            elem = elem.copy()
            elem.nullable = True
        return T("array", nullable, elem=elem, fixed=fixed)

    # -- constant expressions ------------------------------------------------------------------

    def value_of(self, decl, name, where):
        key = (decl.fq, name)
        if key in self._values:
            v = self._values[key]
            if v is None:
                raise GenError("%s: %s.%s refers to itself" % (where, decl.fq, name))
            return v
        self._values[key] = None
        if decl.kind == "enum":
            names = [e[0] for e in decl.enumerators]
            if name not in names:
                raise GenError("%s: %s has no %s" % (where, decl.fq, name))
            i = names.index(name)
            _, expr, ewhere = decl.enumerators[i]
            if expr is not None:
                v = self.eval(expr, decl)[0]
            elif i == 0:
                v = 0
            else:
                v = self.value_of(decl, names[i - 1], ewhere) + 1
            if isinstance(v, bool):
                v = int(v)
            if not isinstance(v, int):
                raise GenError("%s: %s.%s is not an integer" % (ewhere, decl.fq, name))
            v = wrap(v, BACKINGS[backing(decl)][1])
        else:
            c = next((c for c in decl.consts if c.name == name), None)
            if c is None:
                raise GenError("%s: %s has no constant %s" % (where, decl.fq, name))
            v = self.const_value(c, decl)
        self._values[key] = v
        return v

    def const_value(self, c, decl):
        t = self.resolve(c.type, decl)
        v = self.eval(c.expr, decl)[0]
        return coerce(v, t, c.where)

    def eval(self, toks, scope):
        """(value, reference): the value of a constant expression, and the (enum decl, name) it
        is when it is only a reference to an enumerator."""
        ev = Evaluator(self, toks, scope)
        v = ev.expr(0)
        if ev.i != len(toks):
            raise GenError("%s: cannot read the expression after %r" % (toks[ev.i].where, toks[ev.i].text))
        ref = None
        if all(t.kind == "id" or t.text == "." for t in toks):
            ref = ev.last_ref
        return v, ref

    def resolve_name(self, dotted, scope, where):
        parts = dotted.split(".")
        if len(parts) == 1:
            s = scope
            while s is not None:
                if s.kind == "enum" and any(e[0] == dotted for e in s.enumerators):
                    return self.value_of(s, dotted, where), (s, dotted)
                if any(c.name == dotted for c in s.consts):
                    return self.value_of(s, dotted, where), None
                s = s.outer
            raise GenError("%s: unknown name %s" % (where, dotted))
        type_name, member = ".".join(parts[:-1]), parts[-1]
        decl = self.lookup(type_name, scope)
        if decl is None:
            raise GenError("%s: unknown type %s" % (where, type_name))
        v = self.value_of(decl, member, where)
        return v, ((decl, member) if decl.kind == "enum" else None)

    # -- what can default -----------------------------------------------------------------------

    def t_defaultable(self, t):
        if t.nullable:
            return True
        if t.kind == "array":
            return t.fixed is None or self.t_defaultable(t.elem)
        if t.kind == "pfd":
            return False
        if t.kind in ("parcelable", "union"):
            return self.defaultable(t.decl)
        return True

    def defaultable(self, d):
        if d.fq in self._defaultable:
            v = self._defaultable[d.fq]
            return True if v is None else v
        self._defaultable[d.fq] = None
        if d.kind == "parcelable":
            v = all(f.default is not None or self.t_defaultable(self.resolve(f.type, d)) for f in d.fields)
        elif d.kind == "union":
            f = d.fields[0]
            v = f.default is not None or self.t_defaultable(self.resolve(f.type, d))
        else:
            v = True
        self._defaultable[d.fq] = v
        return v


def backing(decl):
    b = decl.ann.get("Backing")
    if b is None:
        return "byte"  # AIDL's default backing type
    m = re.search(r'type\s*=\s*"(\w+)"', b)
    if not m or m.group(1) not in BACKINGS:
        raise GenError("%s: unsupported @Backing(%s)" % (decl.where, b))
    return m.group(1)


def wrap(v, bits):
    v &= (1 << bits) - 1
    if v >= 1 << (bits - 1):
        v -= 1 << bits
    return v


def coerce(v, t, where):
    """A constant's value as a value of type t."""
    if t.kind == "prim":
        if t.prim == "boolean":
            return bool(v)
        if t.prim in ("float", "double"):
            if isinstance(v, (bool, int, float)):
                return float(v)
            raise GenError("%s: not a number" % where)
        if t.prim == "char":
            if isinstance(v, str) and len(v) == 1:
                return ord(v)
            if isinstance(v, int):
                return v & 0xFFFF
            raise GenError("%s: not a char" % where)
        if isinstance(v, bool):
            v = int(v)
        if not isinstance(v, int):
            raise GenError("%s: not an integer" % where)
        return wrap(v, PRIMS[t.prim][2])
    if t.kind == "string":
        if not isinstance(v, str):
            raise GenError("%s: not a string" % where)
        return v
    if t.kind == "enum":
        if isinstance(v, bool):
            v = int(v)
        return wrap(v, BACKINGS[backing(t.decl)][1])
    raise GenError("%s: a constant of this type is not supported" % where)


BINARY = {"||": 1, "&&": 2, "|": 3, "^": 4, "&": 5, "==": 6, "!=": 6, "<": 7, ">": 7, "<=": 7, ">=": 7, "<<": 8, ">>": 8, "+": 9, "-": 9, "*": 10, "/": 10, "%": 10}


def c_div(a, b):
    q = abs(a) // abs(b)
    return q if (a >= 0) == (b >= 0) else -q


def unescape(body):
    return bytes(body, "utf-8").decode("unicode_escape")


class Evaluator:
    def __init__(self, model, toks, scope):
        self.m, self.toks, self.scope, self.i = model, toks, scope, 0
        self.last_ref = None

    def peek(self):
        return self.toks[self.i] if self.i < len(self.toks) else None

    def where(self):
        tok = self.peek() or self.toks[-1]
        return tok.where

    def take(self, text=None):
        tok = self.peek()
        if tok is None or (text is not None and tok.text != text):
            raise GenError("%s: expected %r in a constant expression" % (self.where(), text or "more"))
        self.i += 1
        return tok

    def expr(self, min_prec):
        left = self.unary()
        while True:
            tok = self.peek()
            if tok is None or tok.kind != "op":
                return left
            if tok.text == "?" and min_prec == 0:
                self.i += 1
                a = self.expr(0)
                self.take(":")
                b = self.expr(0)
                left = a if left else b
                continue
            prec = BINARY.get(tok.text)
            if prec is None or prec < min_prec:
                return left
            self.i += 1
            right = self.expr(prec + 1)
            left = self.binary(tok, left, right)

    def binary(self, tok, a, b):
        op = tok.text
        if op == "+" and isinstance(a, str) and isinstance(b, str):
            return a + b
        if op in ("||", "&&"):
            return bool(a) or bool(b) if op == "||" else bool(a) and bool(b)
        if op in ("==", "!=", "<", ">", "<=", ">="):
            return {"==": a == b, "!=": a != b, "<": a < b, ">": a > b, "<=": a <= b, ">=": a >= b}[op]
        if isinstance(a, bool):
            a = int(a)
        if isinstance(b, bool):
            b = int(b)
        if isinstance(a, float) or isinstance(b, float):
            if op in ("+", "-", "*", "/"):
                return {"+": a + b, "-": a - b, "*": a * b, "/": a / b}[op]
            raise GenError("%s: %s of a float" % (tok.where, op))
        if not isinstance(a, int) or not isinstance(b, int):
            raise GenError("%s: %s of a non-number" % (tok.where, op))
        if op in ("/", "%") and b == 0:
            raise GenError("%s: division by zero" % tok.where)
        return {
            "|": lambda: a | b, "^": lambda: a ^ b, "&": lambda: a & b,
            "<<": lambda: a << b, ">>": lambda: a >> b, "+": lambda: a + b, "-": lambda: a - b,
            "*": lambda: a * b, "/": lambda: c_div(a, b), "%": lambda: a - c_div(a, b) * b,
        }[op]()

    def unary(self):
        tok = self.take()
        if tok.kind == "op" and tok.text in ("-", "+", "~", "!"):
            v = self.unary()
            if isinstance(v, bool) and tok.text != "!":
                v = int(v)
            return {"-": lambda: -v, "+": lambda: v, "~": lambda: ~v, "!": lambda: not v}[tok.text]()
        if tok.kind == "op" and tok.text == "(":
            v = self.expr(0)
            self.take(")")
            return v
        if tok.kind == "op" and tok.text == "{":
            items = []
            if self.peek() is not None and self.peek().text == "}":
                self.i += 1
                return items
            while True:
                items.append(self.expr(0))
                t = self.take()
                if t.text == "}":
                    return items
                if t.text != ",":
                    raise GenError("%s: expected ',' or '}'" % t.where)
                if self.peek() is not None and self.peek().text == "}":
                    self.i += 1
                    return items
        if tok.kind == "int":
            return int(tok.text.rstrip("lL"), 0)
        if tok.kind == "float":
            return float(tok.text.rstrip("fFdD"))
        if tok.kind == "str":
            return unescape(tok.text[1:-1])
        if tok.kind == "char":
            return unescape(tok.text[1:-1])
        if tok.kind == "id":
            if tok.text == "true":
                return True
            if tok.text == "false":
                return False
            if tok.text == "null":
                return None
            parts = [tok.text]
            while self.peek() is not None and self.peek().text == "." and self.i + 1 < len(self.toks) and self.toks[self.i + 1].kind == "id":
                self.i += 1
                parts.append(self.take().text)
            v, ref = self.m.resolve_name(".".join(parts), self.scope, tok.where)
            self.last_ref = ref
            return v
        raise GenError("%s: unexpected %r in a constant expression" % (tok.where, tok.text))


