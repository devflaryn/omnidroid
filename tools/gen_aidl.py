# Parsing


class Parser:
    def __init__(self, toks):
        self.t, self.i = toks, 0

    def peek(self, k=0):
        return self.t[min(self.i + k, len(self.t) - 1)]

    def next(self):
        tok = self.peek()
        if tok.kind == "eof":
            self.fail("unexpected end of file")
        self.i += 1
        return tok

    def at(self, text, k=0):
        tok = self.peek(k)
        return tok.kind in ("op", "id") and tok.text == text

    def accept(self, text):
        if self.at(text):
            self.i += 1
            return True
        return False

    def expect(self, text):
        if not self.accept(text):
            self.fail("expected %r" % text)

    def fail(self, msg):
        tok = self.peek()
        raise GenError("%s: %s, found %r" % (tok.where, msg, tok.text))

    def ident(self):
        tok = self.peek()
        if tok.kind != "id":
            self.fail("expected a name")
        self.i += 1
        return tok.text

    def qname(self):
        parts = [self.ident()]
        while self.at(".") and self.peek(1).kind == "id":
            self.i += 1
            parts.append(self.ident())
        return ".".join(parts)

    def annotations(self):
        ann = {}
        while self.at("@"):
            self.i += 1
            name = self.qname()
            args = []
            if self.at("("):
                depth = 0
                while True:
                    tok = self.next()
                    if tok.kind == "op" and tok.text == "(":
                        depth += 1
                    elif tok.kind == "op" and tok.text == ")":
                        depth -= 1
                    args.append(tok.text)
                    if depth == 0:
                        break
                args = args[1:-1]
            ann[name] = " ".join(args)
        return ann

    def expr_until(self, stops):
        out, depth = [], 0
        while True:
            tok = self.peek()
            if tok.kind == "eof":
                self.fail("an unterminated expression")
            if depth == 0 and tok.kind == "op" and tok.text in stops:
                break
            if tok.kind == "op" and tok.text in ("(", "{", "["):
                depth += 1
            elif tok.kind == "op" and tok.text in (")", "}", "]"):
                depth -= 1
            out.append(tok)
            self.i += 1
        if not out:
            self.fail("expected an expression")
        return out

    def close_angle(self):
        tok = self.peek()
        if tok.kind == "op" and tok.text == ">":
            self.i += 1
        elif tok.kind == "op" and tok.text == ">>":
            tok.text = ">"  # the first of the two closes this list; the other stays
        else:
            self.fail("expected '>'")

    def type_ref(self):
        ann = self.annotations()
        where = self.peek().where
        name = self.qname()
        args = []
        if self.accept("<"):
            while True:
                args.append(self.type_ref())
                if self.accept(","):
                    continue
                self.close_angle()
                break
        dims = []
        while self.accept("["):
            if self.accept("]"):
                dims.append(None)
            else:
                dims.append(self.expr_until({"]"}))
                self.expect("]")
        return TypeRef(name, args, dims, ann, where)

    def file(self):
        self.expect("package")
        pkg = self.qname()
        self.expect(";")
        imports = []
        while self.accept("import"):
            imports.append(self.qname())
            self.expect(";")
        decls = []
        while self.peek().kind != "eof":
            decls.append(self.decl(pkg, None))
        return pkg, imports, decls

    def decl(self, pkg, outer):
        ann = self.annotations()
        oneway = self.accept("oneway")
        ann.update(self.annotations())
        where = self.peek().where
        kw = self.ident()
        if kw not in DECL_KEYWORDS:
            raise GenError("%s: expected a declaration, found %r" % (where, kw))
        name = self.ident()
        d = Decl(kw, name, pkg, outer, ann, where)
        d.oneway = oneway
        if self.at("<"):
            raise GenError("%s: generic parcelable %s is not supported" % (where, name))
        if self.at(";") or self.at("cpp_header") or self.at("ndk_header") or self.at("rust_type"):
            raise GenError("%s: unstructured parcelable %s is not supported" % (where, name))
        self.expect("{")
        if kw == "enum":
            self.enum_body(d)
        else:
            while not self.accept("}"):
                self.member(d)
        return d

    def enum_body(self, d):
        while not self.accept("}"):
            self.annotations()
            where = self.peek().where
            name = self.ident()
            expr = self.expr_until({",", "}"}) if self.accept("=") else None
            d.enumerators.append((name, expr, where))
            if not self.accept(","):
                self.expect("}")
                break

    def member(self, d):
        start = self.i
        ann = self.annotations()
        if (self.peek().kind == "id" and self.peek().text in DECL_KEYWORDS) or (self.at("oneway") and self.at("interface", 1)):
            self.i = start
            n = self.decl(d.pkg, d)
            d.nested.append(n)
            return
        where = self.peek().where
        if self.accept("const"):
            t = self.type_ref()
            name = self.ident()
            self.expect("=")
            expr = self.expr_until({";"})
            self.expect(";")
            d.consts.append(Const(name, t, expr, where))
            return
        if d.kind == "interface":
            oneway = self.accept("oneway")
            ret = self.type_ref()
            ret.ann.update(ann)
            name = self.ident()
            self.expect("(")
            params = []
            if not self.accept(")"):
                while True:
                    pann = self.annotations()
                    direction = "in"
                    if self.peek().kind == "id" and self.peek().text in ("in", "out", "inout"):
                        direction = self.next().text
                    t = self.type_ref()
                    t.ann.update(pann)
                    params.append(Param(direction, t, self.ident()))
                    if self.accept(")"):
                        break
                    self.expect(",")
            code = None
            if self.accept("="):
                toks = self.expr_until({";"})
                if len(toks) != 1 or toks[0].kind != "int":
                    raise GenError("%s: a transaction id must be an integer" % where)
                code = int(toks[0].text.rstrip("lL"), 0)
            self.expect(";")
            d.methods.append(Method(name, ret, params, oneway or d.oneway, code, where))
            return
        t = self.type_ref()
        t.ann.update(ann)
        name = self.ident()
        default = self.expr_until({";"}) if self.accept("=") else None
        self.expect(";")
        d.fields.append(Field(name, t, default, where))


