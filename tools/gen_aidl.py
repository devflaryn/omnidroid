# The parsed model

DECL_KEYWORDS = ("parcelable", "union", "enum", "interface")


class TypeRef:
    def __init__(self, name, args, dims, ann, where):
        self.name, self.args, self.dims, self.ann, self.where = name, args, dims, ann, where


class Field:
    def __init__(self, name, type_ref, default, where):
        self.name, self.type, self.default, self.where = name, type_ref, default, where


class Const:
    def __init__(self, name, type_ref, expr, where):
        self.name, self.type, self.expr, self.where = name, type_ref, expr, where


class Param:
    def __init__(self, direction, type_ref, name):
        self.direction, self.type, self.name = direction, type_ref, name


class Method:
    def __init__(self, name, ret, params, oneway, code, where):
        self.name, self.ret, self.params, self.oneway, self.code, self.where = name, ret, params, oneway, code, where


class Decl:
    def __init__(self, kind, name, pkg, outer, ann, where):
        self.kind, self.name, self.pkg, self.outer, self.ann, self.where = kind, name, pkg, outer, ann, where
        self.fields, self.consts, self.nested, self.enumerators, self.methods = [], [], [], [], []
        self.oneway = False
        self.imports = []

    @property
    def path(self):
        return (self.outer.path if self.outer else []) + [self.name]

    @property
    def fq(self):
        return self.pkg + "." + ".".join(self.path)

    def all(self):
        yield self
        for n in self.nested:
            yield from n.all()


