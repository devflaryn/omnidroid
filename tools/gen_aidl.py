# ---------------------------------------------------------------------------------------------
# Lexing

TOKEN_RE = re.compile(
    r"""
     (?P<ws>\s+)
    |(?P<lc>//[^\n]*)
    |(?P<bc>/\*.*?\*/)
    |(?P<float>(?:\d+\.\d*|\.\d+)(?:[eE][+-]?\d+)?[fFdD]?|\d+[eE][+-]?\d+[fFdD]?|\d+[fF](?![0-9A-Za-z_]))
    |(?P<int>0[xX][0-9a-fA-F]+[lL]?|\d+[lL]?)
    |(?P<str>"(?:\\.|[^"\\])*")
    |(?P<char>'(?:\\.|[^'\\])')
    |(?P<id>[A-Za-z_][A-Za-z0-9_]*)
    |(?P<op><<|>>|<=|>=|==|!=|&&|\|\||[{}()\[\]<>;,=.@?:+\-*/%&|^~!])
    """,
    re.S | re.X,
)


class Tok:
    __slots__ = ("kind", "text", "where")

    def __init__(self, kind, text, where):
        self.kind, self.text, self.where = kind, text, where

    def __repr__(self):
        return "Tok(%s,%r)" % (self.kind, self.text)


def lex(src, path):
    toks, pos, line = [], 0, 1
    while pos < len(src):
        m = TOKEN_RE.match(src, pos)
        if not m:
            raise GenError("%s:%d: cannot read %r" % (path, line, src[pos:pos + 20]))
        kind = m.lastgroup
        text = m.group(kind)
        if kind not in ("ws", "lc", "bc"):
            toks.append(Tok(kind, text, "%s:%d" % (path, line)))
        line += text.count("\n")
        pos = m.end()
    toks.append(Tok("eof", "", "%s:%d" % (path, line)))
    return toks


