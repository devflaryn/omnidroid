def rfloat(v):
    s = repr(float(v))
    if s in ("inf", "-inf", "nan"):
        raise GenError("a non-finite float constant")
    if "." not in s and "e" not in s:
        s += ".0"
    return s


def rstr(s):
    out = []
    for ch in s:
        if ch in ('"', "\\"):
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def indent(lines, n=1):
    pad = "    " * n
    return [pad + l if l else l for l in lines]


class Emitter:
    def __init__(self, model, package):
        self.m, self.pkg = model, package
        self.counter = 0

    def fresh(self, base):
        self.counter += 1
        return "%s%d" % (base, self.counter)

    def path(self, decl):
        name = rust_name(decl)
        if decl.pkg == self.pkg.name:
            return name
        return "%s::%s" % (module_name(decl.pkg), name)

    def rty(self, t):
        k = t.kind
        if k == "void":
            return "()"
        if k == "array":
            if t.elem.kind == "prim" and t.elem.prim == "byte":
                inner = "Vec<u8>"
            else:
                inner = "Vec<%s>" % self.rty(t.elem)
            return "Option<%s>" % inner if t.nullable else inner
        if k in ("binder", "interface"):
            return "Binder"
        if k == "prim":
            base = PRIMS[t.prim][0]
        elif k == "string":
            base = "String"
        elif k == "pfd":
            base = "Fd"
        else:
            base = self.path(t.decl)
        return "Option<%s>" % base if t.nullable else base

    @staticmethod
    def stability(scope):
        s = scope
        while s is not None:
            if "VintfStability" in s.ann:
                return "crate::binder::STABILITY_VINTF"
            s = s.outer
        return "crate::binder::STABILITY_SYSTEM"

    # -- reading and writing one value ----------------------------------------------------------

    def rd(self, t):
        """A Rust expression reading a value of type t from `r` (a `&mut Reader`)."""
        k = t.kind
        if k == "prim":
            return "r.%s()?" % PRIMS[t.prim][1]
        if k == "string":
            return "r.string16()?" if t.nullable else 'r.string16()?.ok_or(Malformed("a null string"))?'
        if k == "pfd":
            return "Fd::read_nullable(r)?" if t.nullable else "Fd::read(r)?"
        if k in ("binder", "interface"):
            return "Binder::read(r)?" if t.nullable else "Binder::read_required(r)?"
        if k == "enum":
            return "%s::read(r)?" % self.path(t.decl)
        if k in ("parcelable", "union"):
            return "%s::%s(r)?" % (self.path(t.decl), "read_nullable" if t.nullable else "read_value")
        if k == "array":
            e = t.elem
            if e.kind == "prim" and e.prim == "byte":
                opt = "r.byte_array()?.map(<[u8]>::to_vec)"
            elif e.kind == "enum" and backing(e.decl) == "byte":
                opt = "r.byte_array()?.map(|b| b.iter().map(|&x| %s(x as i8)).collect::<Vec<_>>())" % self.path(e.decl)
            elif e.kind == "prim":
                opt = "r.%s()?" % PRIM_ARRAYS[e.prim]
            elif e.kind == "enum":
                method = "i64_array" if backing(e.decl) == "long" else "i32_array"
                opt = "r.%s()?.map(|v| v.into_iter().map(%s).collect::<Vec<_>>())" % (method, self.path(e.decl))
            else:
                opt = "read_vec(r, |r| Ok(%s))?" % self.rd(e)
            if t.fixed is not None:
                opt = "fixed_len(%s, %d)?" % (opt, t.fixed)
            return opt if t.nullable else '%s.ok_or(Malformed("a null array"))?' % opt
        raise GenError("cannot read a %s" % k)

    def wr(self, t, p, scope):
        """Statements writing the value at place p (of type t) to `w` (a `&mut Writer`)."""
        k = t.kind
        if k == "prim":
            return ["w.%s(%s);" % (PRIMS[t.prim][1], p)]
        if k == "string":
            if t.nullable:
                s = self.fresh("s")
                return ["match &%s {" % p, "    Some(%s) => w.string16(%s)," % (s, s), "    None => w.null(),", "}"]
            return ["w.string16(&%s);" % p]
        if k == "pfd":
            return ["Fd::write_nullable(%s.as_ref(), w);" % p] if t.nullable else ["%s.write(w);" % p]
        if k in ("binder", "interface"):
            return ["%s.write(w, %s);" % (p, self.stability(t.decl if k == "interface" else scope))]
        if k == "enum":
            return ["%s.write(w);" % p]
        if k in ("parcelable", "union"):
            if t.nullable:
                return ["%s::write_nullable(%s.as_ref(), w);" % (self.path(t.decl), p)]
            return ["%s.write_value(w);" % p]
        if k == "array":
            e = t.elem

            def body(q):
                if e.kind == "prim" and e.prim == "byte":
                    return ["w.byte_array(&%s);" % q]
                if e.kind == "enum" and backing(e.decl) == "byte":
                    return ["w.byte_array(&%s.iter().map(|x| x.0 as u8).collect::<Vec<u8>>());" % q]
                if e.kind == "prim":
                    return ["w.%s(&%s);" % (PRIM_ARRAYS[e.prim], q)]
                if e.kind == "enum":
                    method = "i64_array" if backing(e.decl) == "long" else "i32_array"
                    return ["w.%s(&%s.iter().map(|x| x.0).collect::<Vec<_>>());" % (method, q)]
                x = self.fresh("x")
                return ["w.i32(%s.len() as i32);" % q, "for %s in %s.iter() {" % (x, q)] + indent(self.wr(e, "(*%s)" % x, scope)) + ["}"]

            if t.nullable:
                v = self.fresh("v")
                return ["match &%s {" % p, "    Some(%s) => {" % v] + indent(body("(*%s)" % v), 2) + ["    }", "    None => w.null(),", "}"]
            return body(p)
        raise GenError("cannot write a %s" % k)

    # -- default values -------------------------------------------------------------------------

    def default_expr(self, t, expr, scope, where):
        if expr is None:
            if t.nullable:
                return "None"
            if t.kind == "array" and t.fixed is not None:
                return "vec![Default::default(); %d]" % t.fixed
            return "Default::default()"
        v, ref = self.m.eval(expr, scope)
        if v is None:
            if not t.nullable:
                raise GenError("%s: null for a non-null value" % where)
            return "None"
        s = self.value_expr(t, v, ref, where)
        return "Some(%s)" % s if t.nullable else s

    def value_expr(self, t, v, ref, where):
        k = t.kind
        if k == "prim":
            c = coerce(v, t, where)
            if t.prim == "boolean":
                return "true" if c else "false"
            if t.prim in ("float", "double"):
                return rfloat(c)
            return str(c)
        if k == "string":
            return "String::from(%s)" % rstr(coerce(v, t, where))
        if k == "enum":
            if ref is not None and ref[0] is t.decl:
                return "%s::%s" % (self.path(t.decl), ref[1])
            return "%s(%d)" % (self.path(t.decl), coerce(v, t, where))
        if k == "array":
            if not isinstance(v, list):
                raise GenError("%s: an array default that is not a list" % where)
            e = t.elem
            items = [self.value_expr(e, x, None, where) for x in v]
            if e.kind == "prim" and e.prim == "byte":
                items = ["%s_u8" % (x if not x.startswith("-") else str(int(x) & 0xFF)) for x in items]
            return "vec![%s]" % ", ".join(items)
        raise GenError("%s: a default value of this type is not supported" % where)

    # -- declarations ---------------------------------------------------------------------------

    def consts_block(self, d):
        out = []
        for c in d.consts:
            t = self.m.resolve(c.type, d)
            v = self.m.const_value(c, d)
            if t.kind == "string":
                out.append("pub const %s: &str = %s;" % (ident(c.name), rstr(v)))
            elif t.kind == "prim":
                out.append("pub const %s: %s = %s;" % (ident(c.name), PRIMS[t.prim][0], self.value_expr(t, v, None, c.where)))
            else:
                raise GenError("%s: a constant of type %s is not supported" % (c.where, c.type.name))
        return out

    def value_helpers(self, name):
        return [
            "",
            "/// The value anywhere else a %s is: its non-null marker, then [`Self::read`]." % name,
            "pub fn read_value(r: &mut Reader<'_>) -> Result<Self, Malformed> {",
            "    if !r.marker()? {",
            '        return Err(Malformed("a null %s"));' % name,
            "    }",
            "    Self::read(r)",
            "}",
            "",
            "/// A `@nullable` value: its marker (0 for null), then [`Self::read`].",
            "pub fn read_nullable(r: &mut Reader<'_>) -> Result<Option<Self>, Malformed> {",
            "    if r.marker()? {",
            "        Ok(Some(Self::read(r)?))",
            "    } else {",
            "        Ok(None)",
            "    }",
            "}",
            "",
            "pub fn write_value(&self, w: &mut Writer) {",
            "    w.marker(true);",
            "    self.write(w);",
            "}",
            "",
            "pub fn write_nullable(v: Option<&Self>, w: &mut Writer) {",
            "    match v {",
            "        Some(v) => v.write_value(w),",
            "        None => w.marker(false),",
            "    }",
            "}",
        ]

    def emit_enum(self, d):
        name = rust_name(d)
        ty, _ = BACKINGS[backing(d)]
        method = {"i8": "i8", "i32": "i32", "i64": "i64"}[ty]
        out = [
            "/// `%s`: an enum backed by `%s`. Its value is kept as sent, so a peer's newer value is representable." % (d.fq, backing(d)),
            "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Default)]",
            "pub struct %s(pub %s);" % (name, ty),
            "",
            "impl %s {" % name,
        ]
        for n, _, where in d.enumerators:
            out.append("    pub const %s: Self = Self(%d);" % (ident(n), self.m.value_of(d, n, where)))
        out += [
            "",
            "    pub fn read(r: &mut Reader<'_>) -> Result<Self, Malformed> {",
            "        Ok(Self(r.%s()?))" % method,
            "    }",
            "",
            "    pub fn write(self, w: &mut Writer) {",
            "        w.%s(self.0);" % method,
            "    }",
            "}",
        ]
        return out

    def emit_parcelable(self, d):
        name = rust_name(d)
        fields = [(field_ident(f.name), self.m.resolve(f.type, d), f) for f in d.fields]
        defaultable = self.m.defaultable(d)
        derive_default = defaultable and all(f.default is None and not (t.kind == "array" and t.fixed is not None and not t.nullable) for _, t, f in fields)
        derives = "Debug, Clone, PartialEq" + (", Default" if derive_default else "")
        out = ["/// `%s`: a parcelable." % d.fq, "#[derive(%s)]" % derives, "pub struct %s {" % name]
        for fname, t, f in fields:
            out.append("    pub %s: %s," % (fname, self.rty(t)))
        out.append("}")
        if defaultable and not derive_default:
            out += ["", "impl Default for %s {" % name, "    fn default() -> Self {", "        Self {"]
            for fname, t, f in fields:
                out.append("            %s: %s," % (fname, self.default_expr(t, f.default, d, f.where)))
            out += ["        }", "    }", "}"]
        body = self.consts_block(d)
        if body:
            body.append("")
        body += [
            "/// The parcelable's body (after its marker): its size, then its fields; fields an older",
            "/// writer did not send keep their defaults, and fields a newer writer added are skipped.",
            "pub fn read(r: &mut Reader<'_>) -> Result<Self, Malformed> {",
            "    let end = r.parcelable_body()?;",
        ]
        for i, (fname, t, f) in enumerate(fields):
            if f.default is not None or self.m.t_defaultable(t):
                missing = self.default_expr(t, f.default, d, f.where)
            else:
                missing = 'return Err(Malformed("%s.%s is missing"))' % (d.name, f.name)
            body.append("    let v%d = if r.within(end) { %s } else { %s };" % (i, self.rd(t), missing))
        body.append("    r.parcelable_end(end)?;")
        body.append("    Ok(Self { %s })" % ", ".join("%s: v%d" % (fname, i) for i, (fname, _, _) in enumerate(fields)))
        body += ["}", "", "/// The parcelable's body: its size, then its fields.", "pub fn write(&self, w: &mut Writer) {", "    let at = w.parcelable_body_start();"]
        for fname, t, f in fields:
            body += indent(self.wr(t, "self.%s" % fname, d))
        body += ["    w.parcelable_end(at);", "}"]
        body += self.value_helpers(d.name)
        out += ["", "impl %s {" % name] + indent(body) + ["}"]
        return out

    def emit_union(self, d):
        name = rust_name(d)
        if not d.fields:
            raise GenError("%s: a union without fields" % d.where)
        fields = [(variant_ident(f.name), self.m.resolve(f.type, d), f) for f in d.fields]
        out = ["/// `%s`: a union." % d.fq, "#[derive(Debug, Clone, PartialEq)]", "pub enum %s {" % name]
        for vname, t, f in fields:
            out.append("    %s(%s)," % (vname, self.rty(t)))
        out.append("}")
        if self.m.defaultable(d):
            vname, t, f = fields[0]
            out += ["", "impl Default for %s {" % name, "    fn default() -> Self {", "        Self::%s(%s)" % (vname, self.default_expr(t, f.default, d, f.where)), "    }", "}"]
        body = self.consts_block(d)
        if body:
            body.append("")
        body += ["/// The field's tag: its index in the declaration.", "pub fn tag(&self) -> i32 {", "    match self {"]
        for i, (vname, _, _) in enumerate(fields):
            body.append("        Self::%s(_) => %d," % (vname, i))
        body += ["    }", "}", ""]
        body += ["/// The union's body (after its marker): its tag, then that field.", "pub fn read(r: &mut Reader<'_>) -> Result<Self, Malformed> {", "    r.enter()?;", "    let v = match r.i32()? {"]
        for i, (vname, t, f) in enumerate(fields):
            body.append("        %d => Self::%s(%s)," % (i, vname, self.rd(t)))
        body += ['        _ => return Err(Malformed("an unknown %s tag")),' % d.name, "    };", "    r.leave();", "    Ok(v)", "}", ""]
        body += ["/// The union's body: its tag, then that field.", "pub fn write(&self, w: &mut Writer) {", "    match self {"]
        for i, (vname, t, f) in enumerate(fields):
            body += ["        Self::%s(v) => {" % vname, "            w.i32(%d);" % i] + indent(self.wr(t, "(*v)", d), 3) + ["        }"]
        body += ["    }", "}"]
        body += self.value_helpers(d.name)
        out += ["", "impl %s {" % name] + indent(body) + ["}"]
        return out

    def method_codes(self, d):
        explicit = [m.code is not None for m in d.methods]
        if any(explicit) and not all(explicit):
            raise GenError("%s: either every method of %s has a transaction id or none has" % (d.where, d.name))
        codes = [m.code if m.code is not None else i + 1 for i, m in enumerate(d.methods)]
        if len(set(codes)) != len(codes):
            raise GenError("%s: %s repeats a transaction id" % (d.where, d.name))
        return codes

    def emit_interface(self, d):
        iname = rust_name(d)
        mod = snake(iname)
        desc = d.fq
        if "Descriptor" in d.ann:
            m = re.search(r'value\s*=\s*("(?:\\.|[^"\\])*")', d.ann["Descriptor"])
            if not m:
                raise GenError("%s: cannot read @Descriptor" % d.where)
            desc = unescape(m.group(1)[1:-1])
        pkg = self.pkg
        codes = self.method_codes(d)
        server, proxy = iname + "Server", iname + "Proxy"
        methods = []
        for m, code in zip(d.methods, codes):
            ret = self.m.resolve(m.ret, d)
            params = []
            seen = set()
            for p in m.params:
                pt = self.m.resolve(p.type, d)
                if pt.kind == "void":
                    raise GenError("%s: a void parameter" % m.where)
                if p.direction != "in" and pt.is_copy() and pt.kind != "array":
                    raise GenError("%s: %s parameter %s of a primitive type" % (m.where, p.direction, p.name))
                pn = local_ident(p.name)
                if pn in seen:
                    raise GenError("%s: parameter %s twice" % (m.where, p.name))
                seen.add(pn)
                params.append((p, pt, pn))
            if m.oneway and (ret.kind != "void" or any(p.direction != "in" for p, _, _ in params)):
                raise GenError("%s: oneway %s returns something" % (m.where, m.name))
            outs = ([ret] if ret.kind != "void" else []) + [pt for p, pt, _ in params if p.direction != "in"]
            if not outs:
                ret_ty = "()"
            elif len(outs) == 1:
                ret_ty = self.rty(outs[0])
            else:
                ret_ty = "(%s)" % ", ".join(self.rty(t) for t in outs)
            methods.append((m, code, ret, params, outs, ret_ty, field_ident(m.name), "TRANSACTION_" + snake(m.name).upper()))
        names = [x[6] for x in methods]
        if len(set(names)) != len(names):
            raise GenError("%s: %s overloads a method name" % (d.where, d.name))

        out = ["/// `%s`: an interface (V%d)." % (d.fq, pkg.version), "pub mod %s {" % mod]
        b = ["use super::*;", ""]
        b += ['pub const DESCRIPTOR: &str = %s;' % rstr(desc), "/// The frozen version this module was generated from.", "pub const VERSION: i32 = %d;" % pkg.version,
              "/// That version's interface hash (`.hash`), which `getInterfaceHash` answers.", "pub const HASH: &str = %s;" % rstr(pkg.hash)]
        consts = self.consts_block(d)
        if consts:
            b += [""] + consts
        b.append("")
        for m, code, *_rest in methods:
            b.append("pub const %s: u32 = %d;" % (_rest[-1], code))
        # -- the server
        b += ["", "/// A server of `%s`. Each method answers one transaction; a method left out answers" % desc,
              "/// `EX_UNSUPPORTED_OPERATION`. `out` and `inout` values follow the return value in the tuple.",
              "pub trait %s: Send + Sync {" % server]
        for i, (m, code, ret, params, outs, ret_ty, fn, cname) in enumerate(methods):
            args = "".join(", %s: %s" % (pn, self.rty(pt)) for p, pt, pn in params if p.direction != "out")
            if i:
                b.append("")
            b.append("    /// `%s`%s (transaction %d)." % (m.name, " (oneway)" if m.oneway else "", code))
            b.append("    fn %s(&self, ctx: &Ctx<'_>%s) -> Result<%s, Status> {" % (fn, args, ret_ty))
            b.append('        Err(Status::unimplemented("%s.%s"))' % (d.name, m.name))
            b.append("    }")
        b.append("}")
        # -- the dispatcher
        b += ["", "/// Answer one transaction to a `%s` served by `svc`." % desc, "#[must_use]",
              "pub fn dispatch(svc: &dyn %s, call: HostCall) -> HostReply {" % server,
              "    if let Some(reply) = meta_reply(call.code, DESCRIPTOR) {",
              "        return reply;",
              "    }",
              "    if !is_user_code(call.code) {",
              "        return unknown_transaction();",
              "    }",
              "    let mut out = Writer::new();",
              "    match answer(svc, &call, &mut out) {",
              "        Ok(true) => out.into_reply(),",
              "        Ok(false) => unknown_transaction(),",
              "        Err(m) => illegal_argument(&m),",
              "    }",
              "}",
              "",
              "/// Serve `svc` on `broker`: the new host service's `ptr`, to answer as `Binder::Host` or to",
              "/// publish with `Broker::add_service_with_stability`.",
              "pub fn serve(broker: &Broker, svc: Arc<dyn %s>) -> u64 {" % server,
              "    broker.create_host_service_objects(move |call| dispatch(&*svc, call))",
              "}",
              "",
              "/// Decode, call, encode; `false` for a code the interface does not have.",
              "fn answer(svc: &dyn %s, call: &HostCall, w: &mut Writer) -> Result<bool, Malformed> {" % server,
              "    let ctx = Ctx { call };",
              "    let r = &mut Reader::with_objects(&call.data, &call.offsets, &call.fds);",
              "    r.interface_token(DESCRIPTOR)?;",
              "    match call.code {"]
        for m, code, ret, params, outs, ret_ty, fn, cname in methods:
            b.append("        %s => {" % cname)
            call_args = []
            for p, pt, pn in params:
                if p.direction == "out":
                    continue
                b.append("            let a_%s = %s;" % (pn.replace("r#", ""), self.rd(pt)))
                call_args.append("a_%s" % pn.replace("r#", ""))
            invoke = "svc.%s(&ctx%s)" % (fn, "".join(", " + a for a in call_args))
            if m.oneway:
                b.append("            // oneway: the caller does not wait, and hears nothing back.")
                b.append("            let _ = %s;" % invoke)
            else:
                b.append("            match %s {" % invoke)
                if not outs:
                    b.append("                Ok(()) => w.status_ok(),")
                else:
                    b.append("                Ok(ret) => {")
                    b.append("                    w.status_ok();")
                    for j, t in enumerate(outs):
                        place = "ret" if len(outs) == 1 else "ret.%d" % j
                        b += indent(self.wr(t, place, d), 5)
                    b.append("                }")
                b.append("                Err(s) => s.write(w),")
                b.append("            }")
            b.append("        }")
        b += ["        GET_INTERFACE_VERSION => {", "            w.status_ok();", "            w.i32(VERSION);", "        }",
              "        GET_INTERFACE_HASH => {", "            w.status_ok();", "            w.string16(HASH);", "        }",
              "        _ => return Ok(false),", "    }", "    Ok(true)", "}"]
        # -- the proxy
        b += ["", "/// A `%s` the host calls: a binder it holds a handle to (e.g. one a guest registered)." % desc,
              "pub struct %s {" % proxy, "    pub broker: Arc<Broker>,", "    pub handle: u32,", "}", "", "impl %s {" % proxy,
              "    #[must_use]", "    pub fn new(broker: Arc<Broker>, handle: u32) -> Self {", "        Self { broker, handle }", "    }"]
        for m, code, ret, params, outs, ret_ty, fn, cname in methods:
            sig = "".join(", %s: %s" % (pn, self.proxy_ty(pt)) for p, pt, pn in params if p.direction != "out")
            names_ = ", ".join(pn for p, pt, pn in params if p.direction != "out")
            b += ["", "    /// `%s`%s." % (m.name, " (oneway: returns once queued)" if m.oneway else ""),
                  "    pub fn %s(&self%s) -> Result<%s, CallError> {" % (fn, sig, "()" if m.oneway else ret_ty),
                  "        let w = encode_%s(%s);" % (fn.replace("r#", ""), names_),
                  "        let offsets = request_offsets(&w)?;"]
            if m.oneway:
                b.append("        self.broker.host_transact_oneway(self.handle, %s, w.data, &offsets).map_err(CallError::Transport)" % cname)
            else:
                b.append("        let reply = self.broker.host_transact(self.handle, %s, w.data, &offsets).map_err(CallError::Transport)?;" % cname)
                b.append("        decode_%s(&reply)" % fn.replace("r#", ""))
            b.append("    }")
        b += ["", "    /// `getInterfaceVersion`.", "    pub fn get_interface_version(&self) -> Result<i32, CallError> {",
              "        let mut w = Writer::new();", "        w.interface_token(DESCRIPTOR);",
              "        let reply = self.broker.host_transact(self.handle, GET_INTERFACE_VERSION, w.data, &[]).map_err(CallError::Transport)?;",
              "        let r = &mut Reader::new(&reply);", "        reply_status(r)?;", "        Ok(r.i32()?)", "    }",
              "", "    /// `getInterfaceHash`.", "    pub fn get_interface_hash(&self) -> Result<String, CallError> {",
              "        let mut w = Writer::new();", "        w.interface_token(DESCRIPTOR);",
              "        let reply = self.broker.host_transact(self.handle, GET_INTERFACE_HASH, w.data, &[]).map_err(CallError::Transport)?;",
              "        let r = &mut Reader::new(&reply);", "        reply_status(r)?;", '        Ok(r.string16()?.ok_or(Malformed("a null string"))?)', "    }", "}"]
        for m, code, ret, params, outs, ret_ty, fn, cname in methods:
            base = fn.replace("r#", "")
            sig = ", ".join("%s: %s" % (pn, self.proxy_ty(pt)) for p, pt, pn in params if p.direction != "out")
            b += ["", "/// `%s`'s request: the interface token, then the `in` and `inout` arguments." % m.name,
                  "#[must_use]", "pub fn encode_%s(%s) -> Writer {" % (base, sig),
                  "    let mut out = Writer::new();", "    let w = &mut out;", "    w.interface_token(DESCRIPTOR);"]
            for p, pt, pn in params:
                if p.direction == "out":
                    continue
                b += indent(self.wr(pt, pn if pt.is_copy() else "(*%s)" % pn, d))
            b += ["    out", "}"]
            if not m.oneway:
                b += ["", "/// `%s`'s reply: the status, then the return value and the `out` and `inout` values." % m.name,
                      "pub fn decode_%s(reply: &[u8]) -> Result<%s, CallError> {" % (base, ret_ty),
                      "    let r = &mut Reader::new(reply);", "    reply_status(r)?;"]
                for j, t in enumerate(outs):
                    b.append("    let v%d = %s;" % (j, self.rd(t)))
                if not outs:
                    b.append("    Ok(())")
                elif len(outs) == 1:
                    b.append("    Ok(v0)")
                else:
                    b.append("    Ok((%s))" % ", ".join("v%d" % j for j in range(len(outs))))
                b.append("}")
        out += indent(b) + ["}", "", "pub use %s::{%s, %s};" % (mod, proxy, server)]
        return out

    def proxy_ty(self, t):
        """A proxy's parameter: a Copy value by value, anything else by reference."""
        if t.is_copy():
            return self.rty(t)
        if t.kind == "array" and not t.nullable:
            if t.elem.kind == "prim" and t.elem.prim == "byte":
                return "&[u8]"
            return "&[%s]" % self.rty(t.elem)
        if t.kind == "string" and not t.nullable:
            return "&str"
        return "&%s" % self.rty(t)

    def emit_decl(self, d):
        if d.kind == "enum":
            return self.emit_enum(d)
        if d.kind == "parcelable":
            return self.emit_parcelable(d)
        if d.kind == "union":
            return self.emit_union(d)
        return self.emit_interface(d)

    def module(self):
        pkg = self.pkg
        lines = [
            HEADER.rstrip("\n"),
            "//! `%s` V%d, from the frozen AIDL API in `tools/aidl/%s/%d/` (interface hash `%s`)." % (pkg.name, pkg.version, pkg.name, pkg.version, pkg.hash),
            FILE_ALLOWS.rstrip("\n"),
            "",
            "use std::sync::Arc;",
            "",
            "use crate::binder::{Broker, HostCall, HostReply};",
            "use crate::hal::aidl::runtime::*;",
            "use crate::hal::parcel::{Malformed, Reader, Writer};",
        ]
        others = sorted({module_name(p.name) for p in self.m.packages if p.name != pkg.name})
        if others:
            lines.append("use crate::hal::aidl::{%s};" % ", ".join(others))
        for top in pkg.decls:
            for d in top.all():
                lines.append("")
                lines += self.emit_decl(d)
        return "\n".join(lines) + "\n"


def check_recursion(model):
    """A parcelable or union that holds itself by value (not through an array) has no size."""
    for d in model.decls.values():
        if d.kind not in ("parcelable", "union"):
            continue
        stack, seen = [d], set()
        while stack:
            x = stack.pop()
            for f in x.fields:
                t = model.resolve(f.type, x)
                if t.kind in ("parcelable", "union"):
                    if t.decl is d:
                        raise GenError("%s: %s holds itself by value, which needs a Box" % (f.where, d.fq))
                    if t.decl.fq not in seen:
                        seen.add(t.decl.fq)
                        stack.append(t.decl)


def check_supported(model):
    """Every type every declaration uses resolves; every problem, with where it is."""
    errors = []
    for d in model.decls.values():
        refs = [(f.type, f.where) for f in d.fields] + [(c.type, c.where) for c in d.consts]
        for m in d.methods:
            refs.append((m.ret, m.where))
            refs += [(p.type, m.where) for p in m.params]
        for tr, where in refs:
            try:
                model.resolve(tr, d)
            except GenError as e:
                errors.append(str(e))
    if errors:
        raise GenError("unsupported AIDL:\n  " + "\n  ".join(sorted(set(errors))))


def mod_rs(model):
    lines = [
        HEADER.rstrip("\n"),
        "//! AIDL interfaces served or called by the host, generated from the frozen API files under",
        "//! `tools/aidl` by `tools/gen_aidl.py`; what they share is `runtime.rs` (hand-written).",
        "",
        "mod runtime;",
        "",
        "pub use runtime::*;",
        "",
    ]
    for pkg in sorted(model.packages, key=lambda p: p.name):
        lines.append("pub mod %s;" % module_name(pkg.name))
    return "\n".join(lines) + "\n"


def generate(aidl_root=AIDL_ROOT, packages=PACKAGES, out_dir=None):
    """The generated files ({file name: text}); written to out_dir when it is given."""
    model = Model()
    for pkg, version in packages:
        model.load(aidl_root, pkg, version)
    check_supported(model)
    check_recursion(model)
    files = {"mod.rs": mod_rs(model)}
    for pkg in model.packages:
        files[module_name(pkg.name) + ".rs"] = Emitter(model, pkg).module()
    if out_dir is not None:
        os.makedirs(out_dir, exist_ok=True)
        for name, text in files.items():
            with open(os.path.join(out_dir, name), "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    return files, model


def stats(model):
    types = interfaces = methods = 0
    for d in model.decls.values():
        if d.kind == "interface":
            interfaces += 1
            methods += len(d.methods)
        else:
            types += 1
    return types, interfaces, methods


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail when the generated files are not up to date")
    args = ap.parse_args(argv)
    try:
        files, model = generate(out_dir=None if args.check else OUT_DIR)
    except GenError as e:
        print("gen_aidl: %s" % e, file=sys.stderr)
        return 1
    if args.check:
        stale = []
        for name, text in files.items():
            path = os.path.join(OUT_DIR, name)
            try:
                with open(path, encoding="utf-8", newline="") as f:
                    if f.read() != text:
                        stale.append(name)
            except FileNotFoundError:
                stale.append(name)
        if stale:
            print("gen_aidl: out of date: %s" % ", ".join(stale), file=sys.stderr)
            return 1
    types, interfaces, methods = stats(model)
    print("gen_aidl: %d packages, %d types, %d interfaces, %d methods" % (len(model.packages), types, interfaces, methods))
    return 0


if __name__ == "__main__":
    sys.exit(main())
