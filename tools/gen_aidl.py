# Resolved types

PRIMS = {
    # AIDL type: (Rust type, Reader/Writer method, bits for integers)
    "boolean": ("bool", "bool", None),
    "byte": ("i8", "i8", 8),
    "char": ("u16", "char16", None),
    "int": ("i32", "i32", 32),
    "long": ("i64", "i64", 64),
    "float": ("f32", "f32", None),
    "double": ("f64", "f64", None),
}
PRIM_ARRAYS = {"boolean": "bool_array", "char": "char16_array", "int": "i32_array", "long": "i64_array", "float": "f32_array", "double": "f64_array"}
BACKINGS = {"byte": ("i8", 8), "int": ("i32", 32), "long": ("i64", 64)}
UNSUPPORTED_TYPES = {
    "ParcelableHolder": "ParcelableHolder",
    "Map": "Map",
    "FileDescriptor": "FileDescriptor (a raw file descriptor)",
    "CharSequence": "CharSequence",
}


class T:
    """A resolved type: kind is prim, string, pfd, binder, enum, parcelable, union, interface,
    array or void."""

    def __init__(self, kind, nullable=False, prim=None, decl=None, elem=None, fixed=None):
        self.kind, self.nullable, self.prim, self.decl, self.elem, self.fixed = kind, nullable, prim, decl, elem, fixed

    def copy(self):
        return T(self.kind, self.nullable, self.prim, self.decl, self.elem, self.fixed)

    def is_copy(self):
        return self.kind in ("prim", "enum", "binder", "interface")


RUST_KEYWORDS = set(
    "as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref "
    "return self Self static struct super trait true type unsafe use where while async await dyn abstract become "
    "box do final macro override priv typeof unsized virtual yield try gen".split()
)
# Names the generated code uses unqualified; an AIDL type may not take one.
RESERVED_TYPE_NAMES = {"Arc", "Broker", "HostCall", "HostReply", "Malformed", "Reader", "Writer", "Ctx", "Status", "Fd", "Binder", "CallError", "Option", "Vec", "String", "Result", "Self"}
# Local names in generated functions; an AIDL parameter of one of these names gets a `_` suffix.
RESERVED_LOCALS = {"r", "w", "out", "reply", "offsets", "svc", "ctx", "call", "ret", "end", "at"}


def snake(name):
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    return s.lower()


def ident(name):
    """A Rust identifier for an AIDL name already in the right case."""
    if name in ("self", "Self", "super", "crate"):
        return name + "_"
    if name in RUST_KEYWORDS:
        return "r#" + name
    return name


def field_ident(name):
    return ident(snake(name))


def local_ident(name):
    s = snake(name)
    if s in RESERVED_LOCALS:
        s += "_"
    return ident(s)


def variant_ident(name):
    return name[:1].upper() + name[1:]


def rust_name(decl):
    return "_".join(decl.path)


def module_name(pkg):
    return pkg.replace(".", "_")


