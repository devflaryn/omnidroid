#!/usr/bin/env python3
"""Generate Rust from frozen AIDL API files: python tools/gen_aidl.py [--check].

Input: the normalized frozen API snapshots (`aidl_api/<package>/<version>/`) vendored under
`tools/aidl/<package>/<version>/` (see each `SOURCE.txt`), with each version's `.hash`.
Output: `crates/omni-linux/src/hal/aidl/mod.rs` and one module per package, e.g.
`android_hardware_graphics_composer3.rs`:

- every parcelable as a struct, every union as an enum, every AIDL enum as a newtype with
  associated consts, each with exact wire (de)serialization in the NDK backend's format
  (`crates/omni-linux/src/hal/parcel.rs` documents the wire);
- every interface as a module with its descriptor, version, hash, constants and transaction codes,
  a server trait (`<I>Server`) and its dispatcher (`dispatch`), and a client proxy (`<I>Proxy`)
  with an `encode_<method>`/`decode_<method>` pair per method.

The runtime they share (`Ctx`, `Status`, `Fd`, `Binder`, `CallError`, ...) is hand-written in
`hal/aidl/runtime.rs`. The output is deterministic; `--check` fails when it is not up to date.
Standard library only.
"""
